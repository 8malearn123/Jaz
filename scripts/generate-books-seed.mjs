// Generates supabase/migrations/20260928020000_books_seed.sql from the book the app
// already holds: chartOfAccounts in src/data/coa.ts, and periodsSeed + openingBook()
// in src/data/ledgerSeed.ts.
//
// Generated rather than hand-written for one reason: the opening book is not a list of
// numbers, it is the OUTPUT of the posting rules applied to the figures the console has
// always shown — finBase, receivables, purchaseInvoices, wasteLog, the cost centres,
// the fixed-asset register. Transcribing 28 entries and 101 lines into SQL by hand
// would fork it immediately. This way the server's opening book and the seed the
// prototype uses are the same book by construction, and verify-books.mjs re-derives
// both and compares them.
//
// Run: npm run seed:books   (writes the migration; apply it with the Supabase tooling)

import { createServer } from 'vite'
import { createHash } from 'node:crypto'
import { writeFile } from 'node:fs/promises'

const OUT = 'supabase/migrations/20260928020000_books_seed.sql'
const OUT_ASSETS = 'supabase/migrations/20260929010000_fixed_assets_seed.sql'

/**
 * A uuid derived from a stable key, not a random one, so re-running the migration is a
 * no-op instead of a second copy of the book. Shaped as a v5 uuid: sha256 of
 * `books:<key>`, with the version and variant bits set as RFC 4122 requires.
 */
export function bookUuid(key) {
  const h = createHash('sha256').update(`books:${key}`).digest()
  const b = Buffer.from(h.subarray(0, 16))
  b[6] = (b[6] & 0x0f) | 0x50
  b[8] = (b[8] & 0x3f) | 0x80
  const hex = b.toString('hex')
  return `${hex.slice(0, 8)}-${hex.slice(8, 12)}-${hex.slice(12, 16)}-${hex.slice(16, 20)}-${hex.slice(20)}`
}

const q = (v) => (v === null || v === undefined ? 'null' : `'${String(v).replace(/'/g, "''")}'`)
const b = (v) => (v ? 'true' : 'false')

const server = await createServer({ server: { middlewareMode: true }, appType: 'custom', logLevel: 'error' })
const coa = await server.ssrLoadModule('/src/data/coa.ts')
const fa = await server.ssrLoadModule('/src/data/fixedAssets.ts')
const seed = await server.ssrLoadModule('/src/data/ledgerSeed.ts')
const { entries } = seed.openingBook()
const accounts = coa.chartOfAccounts
const periods = seed.periodsSeed
const assets = fa.fixedAssetsSeed
await server.close()

/* ── the chart must be insertable in one pass ─────────────────────────────── */
// `parent` is a foreign key to accounts(code), so a parent has to exist before its
// child. Code order happens to give that, because a parent's code is always the
// rounder, smaller number — but "happens to" is not good enough for a generator, so
// it is checked rather than assumed.
const sorted = [...accounts].sort((x, y) => x.code.localeCompare(y.code))
const seen = new Set()
for (const a of sorted) {
  if (a.parent && !seen.has(a.parent)) {
    throw new Error(`chart cannot be inserted in code order: ${a.code} names parent ${a.parent}, which comes later`)
  }
  seen.add(a.code)
}

/* ── the book must be worth seeding ──────────────────────────────────────── */
for (const e of entries) {
  const d = e.lines.reduce((s, l) => s + l.debitMinor, 0)
  const c = e.lines.reduce((s, l) => s + l.creditMinor, 0)
  if (d !== c) throw new Error(`${e.no} is out of balance: ${d} vs ${c}`)
  if (e.lines.length < 2) throw new Error(`${e.no} has ${e.lines.length} line(s)`)
  for (const l of e.lines) {
    const acc = accounts.find((a) => a.code === l.accountCode)
    if (!acc) throw new Error(`${e.no} names account ${l.accountCode}, which is not in the chart`)
    if (!acc.postable) throw new Error(`${e.no} posts to ${l.accountCode}, which is a header`)
  }
}

const out = []
out.push(`-- The chart of accounts, the periods, and the opening book.
--
-- GENERATED by scripts/generate-books-seed.mjs — do not hand-edit. Regenerate with
-- \`npm run seed:books\` if src/data/coa.ts or src/data/ledgerSeed.ts changes.
--
-- The chart is not demo data: it is the spine every posting names, and without it the
-- books cannot accept a single entry, because journal_lines_require_postable() refuses
-- a line whose account is not there. The opening book IS the prototype's book — the
-- figures the executive overview, the collection tab and the purchase desk have always
-- shown, booked through the same posting rules — so the general ledger opens agreeing
-- with the screens that came before it.
--
-- ORDER MATTERS, twice over:
--   * accounts before lines (foreign key, and the postable check).
--   * every period is inserted OPEN, then the entries, then the closed ones are
--     closed. The opening entry is dated 30 June and June is a closed period, so
--     closing first would have journal_entries_period_open() refuse the very entry
--     that opens the book.
--
-- Entry and line ids are derived from the voucher number, so re-running this is a
-- no-op rather than a second copy of the book.

-- ---------------------------------------------------------------- chart (${sorted.length})

insert into public.accounts
  (code, name_en, name_ar, type, normal, parent, postable, active, is_control, contra, cash, vat_role, sort_order)
values`)
out.push(sorted.map((a, i) => `  (${[
  q(a.code), q(a.name.en), q(a.name.ar), q(a.type), q(a.normal), q(a.parent ?? null),
  b(a.postable), b(a.active), b(a.isControl), b(a.contra), b(a.cash), q(a.vatRole ?? null), String(i),
].join(',')})`).join(',\n'))
out.push(`on conflict (code) do nothing;

-- ---------------------------------------------------------------- periods (${periods.length}), all open for now

insert into public.accounting_periods (key, closed)
values`)
out.push(periods.map((p) => `  (${q(p.key)},false)`).join(',\n'))
out.push(`on conflict (key) do nothing;

-- ---------------------------------------------------------------- the opening book (${entries.length} entries, ${entries.reduce((n, e) => n + e.lines.length, 0)} lines)

insert into public.journal_entries
  (id, no, entry_date, source, source_ref, memo_en, memo_ar, party_en, party_ar, posted_by_en, posted_by_ar)
values`)
out.push(entries.map((e) => `  (${[
  q(bookUuid(e.no)), q(e.no), q(e.date), q(e.source), q(e.sourceRef ?? null),
  q(e.memo.en), q(e.memo.ar), q(e.party?.en ?? null), q(e.party?.ar ?? null),
  q(e.by?.en ?? null), q(e.by?.ar ?? null),
].join(',')})`).join(',\n'))
out.push(`on conflict (id) do nothing;

insert into public.journal_lines
  (id, entry_id, account_code, debit_minor, credit_minor, center_id, memo_en, memo_ar, "position")
values`)
const lines = []
for (const e of entries) {
  e.lines.forEach((l, i) => {
    lines.push(`  (${[
      q(bookUuid(`${e.no}#${i}`)), q(bookUuid(e.no)), q(l.accountCode),
      String(l.debitMinor), String(l.creditMinor), q(l.centerId ?? null),
      q(l.memo?.en ?? null), q(l.memo?.ar ?? null), String(i),
    ].join(',')})`)
  })
}
out.push(lines.join(',\n'))

const closed = periods.filter((p) => p.closed)
out.push(`on conflict (id) do nothing;

-- ---------------------------------------------------------------- now close what is closed (${closed.length})
--
-- Last, for the reason given at the top: the opening entry lands in June, and June is
-- shut once the book has been written into it.
`)
for (const p of closed) {
  out.push(`update public.accounting_periods set closed = true, closed_at = ${q(p.closedAt ?? null)}, closed_by_en = ${q(p.closedBy?.en ?? null)}, closed_by_ar = ${q(p.closedBy?.ar ?? null)} where key = ${q(p.key)};`)
}

await writeFile(OUT, out.join('\n') + '\n')
console.log(`${OUT}: ${sorted.length} accounts, ${periods.length} periods (${closed.length} closed), ${entries.length} entries, ${lines.length} lines`)

/* ── the register ─────────────────────────────────────────────────────────── */
// Generated from the same source for the same reason: the opening entry capitalises
// exactly these costs, and openingAccumulated() over exactly these assets is the credit
// to 1490 in it. A hand-typed register would drift from the balance sheet it explains.
//
// Every seeded asset carries opening_months > 0, which is what the delete guard reads as
// "the book opened holding this". That is asserted in verify-books.mjs rather than left
// as a coincidence of the data.
for (const a of assets) {
  if (!(a.openingMonths > 0)) {
    throw new Error(`${a.id} has openingMonths = 0, so the delete guard would not protect an asset the opening entry capitalises`)
  }
}

const assetSql = [`-- The fixed-asset register.
--
-- GENERATED by scripts/generate-books-seed.mjs — do not hand-edit. Regenerate with
-- \`npm run seed:books\` if src/data/fixedAssets.ts changes.
--
-- These four are the assets the opening entry capitalises: their costs are its debits to
-- 1410/1420/1430 and the sum of openingAccumulated() over them is its credit to 1490. So
-- the register is not decoration beside the balance sheet, it is what explains it — which
-- is why it is generated from the same module rather than typed out again.

insert into public.fixed_assets
  (id, name_en, name_ar, category, cost_minor, life_months, in_service_en, in_service_ar, opening_months, center_id)
values`]
assetSql.push(assets.map((a) => `  (${[
  q(a.id), q(a.name.en), q(a.name.ar), q(a.category),
  String(a.costMinor), String(a.lifeMonths),
  q(a.inService.en), q(a.inService.ar), String(a.openingMonths), q(a.centerId ?? null),
].join(',')})`).join(',\n'))
assetSql.push('on conflict (id) do nothing;')

await writeFile(OUT_ASSETS, assetSql.join('\n') + '\n')
console.log(`${OUT_ASSETS}: ${assets.length} assets, cost ${assets.reduce((t, a) => t + a.costMinor, 0)}, opening accumulated ${assets.reduce((t, a) => t + fa.openingAccumulated(a), 0)}`)
